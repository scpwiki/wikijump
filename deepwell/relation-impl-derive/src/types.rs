//! Helper structures in settings parsing and code generation.

use crate::util::{make_error, make_ident};
use proc_macro2::{Punct, Spacing, Span, TokenStream};
use quote::{ToTokens, TokenStreamExt};
use syn::parse::ParseStream;
use syn::token::Pub;
use syn::{Ident, Visibility};

/// Represents which variant of `RelationObject` is to be used.
#[derive(Debug, Copy, Clone, PartialEq, Eq)]
pub enum RelationObjectType {
    Site,
    User,
    Page,
    File,
}

impl RelationObjectType {
    pub fn parse(input: ParseStream) -> syn::Result<Self> {
        let token = input.parse::<Ident>()?.to_string();
        match token.as_str() {
            "Site" => Ok(RelationObjectType::Site),
            "User" => Ok(RelationObjectType::User),
            "Page" => Ok(RelationObjectType::Page),
            "File" => Ok(RelationObjectType::File),
            _ => Err(make_error(format!(
                "invalid relation value '{token}', should match RelationObject",
            ))),
        }
    }

    pub fn value(self) -> &'static str {
        match self {
            RelationObjectType::Site => "Site",
            RelationObjectType::User => "User",
            RelationObjectType::Page => "Page",
            RelationObjectType::File => "File",
        }
    }
}

impl ToTokens for RelationObjectType {
    fn to_tokens(&self, tokens: &mut TokenStream) {
        // RelationObject
        tokens.append(make_ident("RelationObject"));

        // Double colon `::`
        tokens.append(Punct::new(':', Spacing::Joint));
        tokens.append(Punct::new(':', Spacing::Alone));

        // which type variant
        tokens.append(make_ident(self.value()));
    }
}

/// Designates how this method should be generated by the macro.
#[derive(Debug, Copy, Clone, PartialEq, Eq)]
pub enum GenerateMethod {
    /// Implement a public method to be used.
    Public,

    /// Implement a private "inner" method and private struct, as well as a public struct.
    PrivateWithStruct,

    /// Implement a private "inner" method and private struct only.
    PrivateWithoutStruct,

    /// Don't implement the method, have the caller do it themselves.
    Skip,
}

impl GenerateMethod {
    pub fn parse(input: ParseStream) -> syn::Result<Self> {
        let value = input.parse::<Ident>()?.to_string();
        match value.as_str() {
            "public" => Ok(GenerateMethod::Public),
            "private" => Ok(GenerateMethod::PrivateWithStruct),
            "private_only" => Ok(GenerateMethod::PrivateWithoutStruct),
            "skip" => Ok(GenerateMethod::Skip),
            _ => Err(make_error(format!("invalid generation setting: {value}"))),
        }
    }

    pub fn settings(self) -> Option<GenerateMethodSettings> {
        match self {
            GenerateMethod::Public => Some(GenerateMethodSettings {
                fn_public: true,
                fn_visibility: public(),
                fn_suffix: "",
                generate_pub_struct: true,
            }),
            GenerateMethod::PrivateWithStruct => Some(GenerateMethodSettings {
                fn_public: false,
                fn_visibility: private(),
                fn_suffix: "_inner",
                generate_pub_struct: true,
            }),
            GenerateMethod::PrivateWithoutStruct => Some(GenerateMethodSettings {
                fn_public: false,
                fn_visibility: private(),
                fn_suffix: "_inner",
                generate_pub_struct: false,
            }),
            GenerateMethod::Skip => None,
        }
    }
}

impl Default for GenerateMethod {
    #[inline]
    fn default() -> Self {
        GenerateMethod::Public
    }
}

/// Helper struct used in token expansion.
/// Contains redundant fields for convenience.
pub struct GenerateMethodSettings {
    pub fn_public: bool,
    pub fn_visibility: Visibility,
    pub fn_suffix: &'static str,
    pub generate_pub_struct: bool,
}

#[inline]
fn public() -> Visibility {
    Visibility::Public(Pub(Span::call_site()))
}

#[inline]
fn private() -> Visibility {
    Visibility::Inherited
}
