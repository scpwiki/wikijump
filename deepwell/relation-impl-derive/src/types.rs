use crate::util::{make_error, make_ident};
use proc_macro2::{Span, TokenStream};
use quote::{ToTokens, TokenStreamExt};
use syn::parse::ParseStream;
use syn::token::Pub;
use syn::{Ident, LitBool, Token, Visibility};

/// Represents which variant of `RelationObject` is to be used.
#[derive(Debug, Copy, Clone, PartialEq, Eq)]
pub enum RelationObjectType {
    Site,
    User,
    Page,
    File,
}

impl RelationObjectType {
    pub fn parse(input: ParseStream) -> syn::Result<Self> {
        let token = input.parse::<Ident>()?.to_string();
        match token.as_str() {
            "Site" => Ok(RelationObjectType::Site),
            "User" => Ok(RelationObjectType::User),
            "Page" => Ok(RelationObjectType::Page),
            "File" => Ok(RelationObjectType::File),
            _ => Err(make_error(format!(
                "invalid relation value '{token}', should match RelationObject",
            ))),
        }
    }

    pub fn value(self) -> &'static str {
        match self {
            RelationObjectType::Site => "Site",
            RelationObjectType::User => "User",
            RelationObjectType::Page => "Page",
            RelationObjectType::File => "File",
        }
    }
}

impl ToTokens for RelationObjectType {
    fn to_tokens(&self, tokens: &mut TokenStream) {
        tokens.append(make_ident(self.value()))
    }
}

/// Designates how this method should be generated by the macro.
#[derive(Debug, Copy, Clone, PartialEq, Eq)]
pub enum GenerateMethod {
    /// Implement a public method to be used.
    Public,

    /// Implement a private "inner" method as a helper.
    Private,

    /// Don't implement the method or struct, have the caller do it themselves.
    Skip,
}

impl GenerateMethod {
    pub fn parse(input: ParseStream) -> syn::Result<Self> {
        let token = input.lookahead1();
        if token.peek(LitBool) {
            let t_bool: LitBool = input.parse()?;
            if t_bool.value {
                Ok(GenerateMethod::Public)
            } else {
                Ok(GenerateMethod::Private)
            }
        } else if token.peek(Token![extern]) {
            let _: Token![extern] = input.parse()?;
            Ok(GenerateMethod::Skip)
        } else {
            Err(token.error())
        }
    }

    pub fn vis_and_suffix(self) -> Option<(Visibility, &'static str)> {
        match self {
            GenerateMethod::Public => Some((public(), "")),
            GenerateMethod::Private => Some((private(), "_inner")),
            GenerateMethod::Skip => None,
        }
    }
}

impl Default for GenerateMethod {
    #[inline]
    fn default() -> Self {
        GenerateMethod::Public
    }
}

#[inline]
fn public() -> Visibility {
    Visibility::Public(Pub(Span::call_site()))
}

#[inline]
fn private() -> Visibility {
    Visibility::Inherited
}
